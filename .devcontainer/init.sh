#!/usr/bin/env bash
# Host-side devcontainer initializeCommand.
#
# Generates the ignored Compose override used for host-specific settings:
#   - worktree Git metadata mounted at the same absolute host path; and
#   - NVIDIA runtime/device reservations when the host Docker daemon exposes
#     the nvidia runtime.
#
# A normal CPU-only clone receives a no-op override. Idempotent and safe to
# re-run. See wiki: patterns/devcontainer-worktree-git-mount.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WS_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
OUT="$SCRIPT_DIR/docker-compose.worktree.yml"
TEMPLATE="$SCRIPT_DIR/docker-compose.worktree.yml.in"
GIT_PATH="$WS_DIR/.git"

main_git=""
if [ -f "$GIT_PATH" ]; then
  gitdir="$(sed -n 's/^gitdir: //p' "$GIT_PATH")"
  if [ -n "$gitdir" ]; then
    main_git="$(cd "$(dirname "$gitdir")/.." && pwd)"
  else
    echo "[init] .git has no gitdir pointer; skipping worktree mount" >&2
  fi
fi

nvidia_runtime=false
if command -v docker >/dev/null 2>&1 \
    && docker info --format '{{json .Runtimes}}' 2>/dev/null \
       | grep -q '"nvidia"'; then
  nvidia_runtime=true
fi

if [ -z "$main_git" ] && [ "$nvidia_runtime" = false ]; then
  cp "$TEMPLATE" "$OUT"
  echo "[init] normal CPU-only clone; no host override needed"
  exit 0
fi

{
  echo "# GENERATED by .devcontainer/init.sh — do not edit or commit."
  echo "services:"
  echo "  app:"
  if [ "$nvidia_runtime" = true ]; then
    cat <<'EOF'
    runtime: nvidia
    deploy:
      resources:
        reservations:
          devices:
            - driver: nvidia
              count: all
              capabilities: [gpu]
EOF
  fi
  if [ -n "$main_git" ]; then
    echo "    volumes:"
    echo "      - ${main_git}:${main_git}:cached"
  fi
} > "$OUT"

if [ -n "$main_git" ]; then
  echo "[init] worktree detected; mounting ${main_git} at identity path"
fi
if [ "$nvidia_runtime" = true ]; then
  echo "[init] NVIDIA Docker runtime detected; enabling GPU passthrough"
else
  echo "[init] NVIDIA Docker runtime unavailable; using CPU-only container"
fi
